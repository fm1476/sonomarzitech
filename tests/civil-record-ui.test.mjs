import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../frontend/assets/js/modules/civil-record-ui.js',import.meta.url),'utf8');
const context={window:{}};vm.createContext(context);vm.runInContext(source,context);
const ui=context.window.SonoMarziCivilRecordUI;
const facts=ui.facts([{label:'Plaintiff',value:'<script>alert(1)</script>'},{label:'Open claims',value:0}]);
assert.doesNotMatch(facts,/<script>/);assert.match(facts,/&lt;script&gt;/);
assert.match(facts,/Open claims/);assert.match(facts,/class="v">0/);
const addresses=ui.addresses([{address:'123 Fictional Lane',isPrimary:true},{address:'987 Training Way'}],{idPrefix:'ca',selected:1});
assert.match(addresses,/caServiceAddressMap/);assert.match(addresses,/data-ca-address-idx="1"/);
assert.match(addresses,/987%20Training%20Way/);assert.match(addresses,/Open in Maps/);
assert.equal((addresses.match(/class="civil-address-chip/g)||[]).length,2);
assert.match(ui.addresses([],{idPrefix:'paper'}),/No service address recorded/);
const general=await readFile(new URL('../frontend/assets/js/modules/civil.js',import.meta.url),'utf8');
const view=await readFile(new URL('../frontend/assets/js/modules/civil-california-view.js',import.meta.url),'utf8');
assert.match(general,/SonoMarziCivilRecordUI\.facts/);assert.match(general,/SonoMarziCivilRecordUI\.addresses/);
assert.match(view,/SonoMarziCivilRecordUI\.facts/);assert.match(view,/SonoMarziCivilRecordUI\.addresses/);
console.log('Shared Civil record facts, multi-address map, escaped fields and zero values passed.');
