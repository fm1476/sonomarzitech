import assert from 'node:assert/strict';
import {validateTestIntake as intake,validateTestTransition as transition} from '../lambdas/api/lib/civil-test-validation.mjs';
const record={caseNumber:'TEST-001',courtOfOrigin:'Fictional court',defendant:'Demo defendant',plaintiff:'Demo plaintiff',signedInstructions:'Fictional instructions',receivedDate:'2026-10-17',serviceAddresses:[{address:'123 Example Street'}]};
assert.deepEqual(intake(record),[]);
for(const receivedDate of ['2026-02-30','2026-13-01','garbage',true]) assert.ok(intake({...record,receivedDate}).length);
for(const value of [' ',true,{},[]]) assert.ok(intake({...record,signedInstructions:value}).length);
assert.ok(intake({...record,serviceAddresses:[{address:' '}]}).length);
assert.ok(intake({...record,note:'x'.repeat(20001)}).length);
assert.ok(transition('assigned',{},record,'A').length);
assert.deepEqual(transition('assigned',{note:'Fictional assignment',assignedTo:'Demo officer'},record,'A'),[]);
assert.ok(transition('attempted',{note:'Test',attemptDate:'2026-02-30',attemptTime:'25:00',attemptResult:'No contact'},record,'A').length);
const evidence={note:'Fictional service',serviceMethod:'Personal Service',servedDate:'2026-10-17',servedTime:'12:00',servedOnName:'Demo defendant',serverIdentity:'Demo officer'};
assert.deepEqual(transition('served',evidence,record,'A'),[]);
assert.ok(transition('served',{...evidence,serviceMethod:'made up'},record,'A').length);
assert.ok(transition('served',{...evidence,serviceMethod:'Substituted Service'},record,'A').length);
assert.ok(transition('served',{...evidence,serviceMethod:'Posting (Nail and Mail)'},record,'A').length);
assert.ok(transition('served',[],record,'A').length);
const served={...record,testHistory:[{stage:'served',actor:'A',evidence}]};
const review={note:'Reviewed fictional evidence',approvalReference:'TEST-APPROVAL'};
assert.ok(transition('reviewed',review,served,'A').length);
assert.ok(transition('reviewed',review,record,'B').length);
assert.deepEqual(transition('reviewed',review,served,'B'),[]);
const closed={note:'Fictional return only',returnReference:'TEST-RETURN',returnedDate:'2026-10-17'};
assert.ok(transition('closed',closed,served,'B').length);
assert.deepEqual(transition('closed',closed,{...served,testHistory:[...served.testHistory,{stage:'reviewed',actor:'B',evidence:review}]},'B'),[]);
console.log('Civil Demo evidence validation passed: intake, dates, assignment, attempts, service methods, independent review and closure.');
