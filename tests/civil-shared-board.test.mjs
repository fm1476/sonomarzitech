import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('../frontend/assets/js/modules/civil-board-ui.js',import.meta.url),'utf8');
const context={window:{}};vm.createContext(context);vm.runInContext(source,context);
const ui=context.window.SonoMarziCivilBoardUI;
const cases=[{id:'one',caseNumber:'CA-1',paperType:'Summons',defendant:'Demo Defendant',stage:'Intake',returnByDate:'2026-10-29'},{id:'two',caseNumber:'CA-2',paperType:'Writ',defendant:'Demo Respondent',stage:'Reviewed',returnByDate:'2026-10-30'}];
assert.equal(ui.groupStage('Intake'),'Unassigned');
assert.equal(ui.groupStage('Reviewed'),'Return Processing');
assert.equal(ui.groupStage('Attempting'),'Attempting');
const html=ui.columns({items:cases,group:p=>ui.groupStage(p.stage),renderCard:p=>'<button data-case="'+p.id+'">'+p.caseNumber+'</button>'});
assert.match(html,/Unassigned/);assert.match(html,/Return Processing/);
assert.match(html,/data-case="one"/);assert.match(html,/data-case="two"/);
const table=ui.table({items:cases});assert.match(table,/CA-1/);assert.match(table,/CA-2/);assert.match(table,/Return By/);
const filtered=ui.filters({ids:{search:'s',type:'t',location:'l'},types:['Summons'],locations:['Sonoma'],query:'<script>'});
assert.doesNotMatch(filtered,/<script>/);assert.match(filtered,/&lt;script&gt;/);
assert.match(ui.switcher('table'),/aria-pressed="true"/);
const general=await readFile(new URL('../frontend/assets/js/modules/civil.js',import.meta.url),'utf8');
const california=await readFile(new URL('../frontend/assets/js/modules/civil-california.js',import.meta.url),'utf8');
assert.match(general,/SonoMarziCivilBoardUI\.columns/);
assert.match(california,/SonoMarziCivilBoardUI\.columns/);
assert.match(general,/SonoMarziCivilBoardUI\.table/);
assert.match(california,/SonoMarziCivilBoardUI\.table/);
assert.match(california,/civil-board/);
assert.match(california,/api\("get", \{ id: caseId \}/);
assert.doesNotMatch(california,/data-stage-dropzone.*addEventListener/);
assert.match(ui.styles,/civil-shared-filters input\[type="search"\]/,'Shared dark search input must receive explicit styling');
assert.match(ui.styles,/grid-template-columns:repeat\(3,minmax\(0,1fr\)\)/,'Laptop grid must wrap status columns');
assert.match(ui.styles,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/,'Compact grid must wrap status columns');
console.log('Shared Civil presentation, Kanban/Table modes, case grouping and escaped search filters passed.');
