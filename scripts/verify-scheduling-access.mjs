import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {viewsGroup, scheduleWriteDecision, filterSchedulingRecords} from '../lambdas/api/lib/scheduling-access.mjs';
const patrol = {id:'patrol',visibility:'unit',unitNames:['Patrol'],managerIds:['scheduler'],viewerIds:[]};
const dispatch = {id:'dispatch',visibility:'selected',managerIds:['dispatchScheduler'],viewerIds:['dispatcher']};
const shift = {id:'p',workGroupId:'patrol'};
const snapshot = {'pm.scheduleWorkGroups':[patrol,dispatch], 'pm.scheduleShifts':[shift,{id:'d',workGroupId:'dispatch'}],personnel:[{id:'officer',unit:'Patrol'}]};
assert.equal(viewsGroup(patrol,{unit:'  PATROL '},'officer'),true);
assert.equal(viewsGroup(patrol,{unit:'Highway Patrol'},'officer'),false);
assert.equal(viewsGroup(patrol,{unit:''},'officer'),false);
const decision = (collection,value,before,id='scheduler',abilities=['pm_schedule_manage']) => scheduleWriteDecision(collection,{itemId:value?.id || 'row',value,deleted:false},before,snapshot,id,a=>abilities.includes(a));
assert.equal(decision('pm.scheduleShifts',shift,shift).allowed,true);
assert.equal(decision('pm.scheduleShifts',{id:'d',workGroupId:'dispatch'},{id:'d',workGroupId:'dispatch'}).allowed,false);
assert.equal(decision('pm.scheduleShifts',{...shift,workGroupId:'dispatch'},shift).allowed,false);
assert.equal(decision('pm.scheduleAssignments',{id:'a',shiftId:'d'}).allowed,false);
assert.equal(decision('pm.scheduleWorkGroups',patrol,patrol).allowed,false);
const opportunity = {id:'ot',shiftId:'p',status:'open',requests:[]};
const request = {...opportunity,requests:[{personId:'officer',status:'pending',requestedAt:'now'}]};
assert.equal(decision('pm.overtimeOpportunities',request,opportunity,'officer',['pm_overtime_optin']).allowed,true);
assert.equal(decision('pm.overtimeOpportunities',{...request,date:'2026-12-01'},opportunity,'officer',['pm_overtime_optin']).allowed,false);
assert.equal(decision('pm.overtimeOpportunities',{...request,requests:[{personId:'another',status:'pending'}]},opportunity,'officer',['pm_overtime_optin']).allowed,false);
assert.equal(decision('pm.overtimeOpportunities',{...request,requests:{}},opportunity,'officer',['pm_overtime_optin']).allowed,false);
assert.equal(decision('pm.overtimeOpportunities',request,request,'officer',['pm_overtime_optin']).allowed,false);
const row=(collection,value)=>({key:JSON.stringify([collection.split('.'),value.id]),value,deleted:false});
const rows=[...snapshot['pm.scheduleWorkGroups'].map(v=>row('pm.scheduleWorkGroups',v)),...snapshot['pm.scheduleShifts'].map(v=>row('pm.scheduleShifts',v)),row('personnel',snapshot.personnel[0]),row('pm.overtimeOpportunities',opportunity),row('pm.overtimeOpportunities',{id:'dispatchOt',shiftId:'d'}),{key:JSON.stringify([['pm','scheduleShifts'],'$order']),value:['p','d']}];
const visible=filterSchedulingRecords(rows,'officer',true);
assert(!visible.some(r=>r.value?.id==='dispatch'||r.value?.id==='d'||r.value?.id==='dispatchOt'));
assert.deepEqual(visible.find(r=>JSON.parse(r.key)[1]==='$order').value,['p']);
const own=filterSchedulingRecords([...rows,row('pm.scheduleAssignments',{id:'own',personId:'officer',shiftId:'d'})],'officer',false);
assert(own.some(r=>r.value?.id==='d'));
assert(!own.some(r=>r.value?.id==='dispatchOt'));
// Execute the actual browser access helpers without loading the application's DOM.
const source=fs.readFileSync('frontend/assets/js/modules/personnel.js','utf8');
const start=source.indexOf('function currentPerson()');
const end=source.indexOf('function visibleScheduleWorkGroups()',start);
const context={STATE:{personnel:snapshot.personnel,pm:{scheduleWorkGroups:snapshot['pm.scheduleWorkGroups']}},CURRENT_USER_ID:'officer',can:()=>false};
vm.createContext(context);vm.runInContext(source.slice(start,end),context);
assert.equal(context.canViewWorkGroup(patrol),true);
assert.equal(context.canViewWorkGroup(dispatch),false);
context.CURRENT_USER_ID='scheduler';context.can=a=>a==='pm_schedule_manage';
assert.equal(context.canManageScheduleShift(shift),true);
assert.equal(context.canManageScheduleShift({id:'d',workGroupId:'dispatch'}),false);
console.log('Scheduling access regression checks passed.');
